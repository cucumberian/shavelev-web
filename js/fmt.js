/* fmt.js — печать чисел как rtcRound(x,n) в программе «Таблицы Шевелева», разделитель — запятая.
   Вынесено из calc.js (13.10.2026) потому, что модули данных страниц (js/data/*.js) подключаются
   в index.html ДО calc.js и не могут вызвать fmt() из движка: подписи строк («dн=88,5 мм») строит
   страница материала, а не общий UI. Файл подключается первым <script>.

   Модель совместимости та же, что у остальных модулей: в браузере — обычные глобалы, в node —
   module.exports; calc.js в node подставляет их себе сам (см. его шапку), поэтому тестам ничего
   менять не пришлось. */
"use strict";

/* fmt — как rtcRound(x,n): округление до n знаков, хвостовые нули отбрасываются. Малые значения
   (0 < |x| < 10^-n) печатаются с дополнительными знаками, чтобы не округляться в ноль (BUG-7):
   оригинал печатает «0,001 м» при H = 0,000764 (rtcRound), клон — «0,00076366559». */
function fmt(x,n){
  if(x!==0 && Math.abs(x)<Math.pow(10,-n)){
    let s=x.toFixed(n+8).replace(/0+$/,'').replace(/\.$/,'');
    return s.replace('.',',');
  }
  return (Math.round(x*Math.pow(10,n))/Math.pow(10,n)).toString().replace('.',',');
}
/* fmt2 — ровно 2 знака с запятой (строки рекомендации по ряду: «2,00 л/сек = 7,20 м куб/х») */
function fmt2(x){return x.toFixed(2).replace('.',',');}
/* fmt3 — ровно 3 знака, хвостовые нули НЕ отбрасываются (запрос 08.10.2026: «2,010 так и пиши»).
   Им печатаются R и ΔP на страницах меди и PEX (СП 40-108-2004 (5), СП 41-109-2005 (3)). */
function fmt3(x){return x.toFixed(3).replace('.',',');}
/* vbs — печать числа как VB6 Str(): точка вместо запятой, хвостовые нули отброшены.
   Строки рекомендации а/ц и пластика (frmtablII4/frmtablII5) печатаются программой именно так:
   «При расходе 3л/сек =10.8м куб/ч …» — без пробелов вокруг знаков. */
function vbs(x){ return String(Math.round(x*100)/100); }
/* vbsc — тот же VB6 Str(), но с десятичной ЗАПЯТОЙ. Строки рекомендации ж/б (frmtablII7) печатаются
   так: «…=118,8м куб/ч,…» (кадр recA_q33), тогда как а/ц той же программы печатает точку:
   «=28.8м куб/ч» (кадр ac_rec2_du200_q8). Разница реальная, обе ветки в EXE свои. */
function vbsc(x){ return vbs(x).replace('.', ',');}

/* экспорт для node-тестов (в браузере window есть, в node — global) */
if (typeof module!=='undefined' && module.exports){
  module.exports={fmt,fmt2,fmt3,vbs,vbsc};
}