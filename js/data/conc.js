/* js/data/conc.js — напорные железобетонные трубы (frmtablII7?, ГОСТ 12586.0-83).
   Данные — реверс shev.exe (BSTR-списки комбо + пулы f64); комментарии указывают
   VA-адреса находки. */
"use strict";

 const MAT_CONC = {id:'conc',     name:'Напорные железобетонные ГОСТ 12586.0-83',            doc:'g12586',
  // Список комбо — AddItem-последовательность загрузки ж/б-страницы (FUN_005022c0 и её дубль
  // FUN_005082f0: 500,600,700,800,900,1000,1200,1400,1600, индексы 0..8 — единственный такой
  // список в бинаре). dв = dу (скрин оригинала 06.10.2026: d=600 → dp=600). Диаметров 100…400
  // на странице НЕТ: ГОСТ 12586.0-83 — напорные ж/б трубы DN 500…1600; прежний список 100..1600
  // был домыслом (в комбо-строке EXE число AddItem = 9, а не 15).
  d:[500,600,700,800,900,1000,1200,1400,1600], dvSame:true,
  // Карта видимости блоков страницы: режима/теплоносителя/k/«новые-неновые» в окне нет (H = i·L)
  ui:{sys:false, wear:false, cu:false}}


/* page — поведение страницы (рефакторинг 13.10.2026): чистые функции, без DOM.
   У напорных ж/б труб dв = dу: в окне нет ни наружного диаметра, ни толщины стенки (ГОСТ 12586.0-83),
   комбо — это готовые условные проходы, и программа печатает то же число в dв (живой скрин 06.10.2026:
   d=600 → dp=600). Рекомендация идёт по этому же ряду.
   d — #dsel хранит dу (он же dв). */
MAT_CONC.page={
  labels:{d:'Внутренний диаметр, мм:', dv:'Расчётный внутренний диаметр dp, мм:'},
  rows(){ return MAT_CONC.d.map(d=>[d,'dв='+d+' мм']); },
  // У напорных ж/б труб dв = dу: в окне нет ни наружного диаметра, ни толщины стенки (ГОСТ 12586.0-83),
  // комбо — это готовые условные проходы, и программа печатает то же число в dв (живой скрин 06.10.2026:
  // d=600 → dp=600). Рекомендация идёт по этому же ряду.
  dvOf(st,d){ return +d; },
  gated:true,
  rec:{mode:'vel', rows:[500,600,700,800,900,1000,1200,1400,1600], clamp:false,
   overflow:()=>'Большая скорость! Рекомендуется использовать трубу с условным проходом более 1600мм'},
};
registerMaterial(MAT_CONC);

/* экспорт для node-тестов */
