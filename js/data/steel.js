/* js/data/steel.js — стальные водогазопроводные трубы (страница frmtablII1, ГОСТ 3262-75).
   Данные — реверс shev.exe (BSTR-списки комбо + пулы f64); комментарии указывают
   VA-адреса находки. */
"use strict";

 // frmtablII1 (газовые, ГОСТ 3262-75): dн — Form_Load 0x4781e8; стенки — Select Case FUN_00478c30;
 // dp = dн − 2s − 1, где 1 мм — коррозия/отложения (help формы, 0x50395)
 const MAT_STEEL = {id:'steel',    name:'Стальные водогазопроводные ГОСТ 3262-75',            doc:'g3262',
  gas:{dn:[10.2,13.5,17,21.3,26.8,33.5,42.3,48,60,75.5,88.5,101.3,114,140,165],
   s:{'10.2':[1.8,2,2.5],'13.5':[2,2.2,2.8],'17':[2,2.2,2.8],'21.3':[2.35,2.5,2.8,3.2],
      '26.8':[2.35,2.5,2.8,3.2],'33.5':[2.8,3.2,4],'42.3':[2.8,3.2,4],'48':[3,3.5,4],
      '60':[3,3.5,4.5],'75.5':[3.2,4,4.5],'88.5':[3.5,4,4.5],'101.3':[3.5,4,4.5],
      '114':[4,4.5,5],'140':[4,4.5,5.5],'165':[4,4.5,5.5]},
   // dу по dн — Таблица 1 кн. Шевелевых 1984 (стр. 8–9); обыкновенная стенка — по книжному dв
   du:{'10.2':6,'13.5':8,'17':10,'21.3':15,'26.8':20,'33.5':25,'42.3':32,'48':40,
       '60':50,'75.5':65,'88.5':80,'101.3':90,'114':100,'140':125,'165':150},
   ord:{'21.3':2.8,'26.8':2.8}},
   // Карта видимости блоков страницы (frmtablII1): стальной блок «Режим / теплоноситель»
   // (Система/местные/режим/k) активен, «Трубы» (новые/неновые) есть, своих медных/PEX-рамок нет.
   // ВАЖНО: карта лежит на самом MAT_STEEL, а не внутри gas — иначе движок её не увидит.
   ui:{sys:true, wear:true, cu:false}}


/* page — поведение страницы (рефакторинг 13.10.2026). Все функции ЧИСТЫЕ: без DOM, без чтения
   контролов; на входе — состояние страницы st (его собирает ui.js из контролов) и значение
   селектора диаметра d. Здесь живёт ЕДИНЫЙ закон «как из наружного диаметра и стенки получается
   расчётный внутренний диаметр dp»: до 13.10.2026 он был написан ДВАЖДЫ в js/ui.js (curDv() для
   выбранного значения и dpOf() для рядов строки рекомендации) и разошёлся на пороге 300 мм у
   чугуна (коммит v0.2.2). Теперь это одна функция, а не две копии.
   d  — у этой страницы #dsel хранит НАРУЖНЫЙ dн (не dв!). */
MAT_STEEL.page={
  // discovery — что о странице сообщает shev-list-materials: ряд диаметров (для серии,
  // выставленной в st), закон dв словами и, где есть, серии/классы труб. Знание здесь, а не в
  // ветвлении инструмента: прежняя цепь в webmcp.js однажды выдала metal-pex текст подписи стекла.
  discovery(st){ return {
    diameters:(this.rows(st)||[]).map(r=>r[0]),
    note:'dp=dн−2s−1 (1 мм коррозия), задавай wall_mm'
  }; },
  labels:{d:'Наружный диаметр dн, мм:', t:'Толщина стенки S, мм:',
          dv:'Расчётный внутренний диаметр dp, мм:'},
  // Комбо — dн (AddItem-последовательность frmtablII1), толщины связаны с выбранным dн
  // (FUN_00478c30, Select Case). Подпись печатается с одним знаком: «дн=88,5 мм».
  rows(){ return MAT_STEEL.gas.dn.map(d=>[d,'dн='+fmt(d,1)+' мм']); },
  wallRows(st,d){ return MAT_STEEL.gas.s[d]||[]; },
  // dp = dн − 2S; «−1 мм» — слой коррозии и отложений, вычитается у «неновых» при ЛЮБОМ диаметре:
  // в книге (стр. 6) для 300 мм и более его не советуют вычитать, но программа вычитает и там —
  // живые точки 12.10.2026: dн=325 S=4 → 316; dн=1120 S=10 → 1099, а при «новых» там же 1100.
  dvOf(st,d){ return d-2*st.S-(st.wear==='old'?1:0); },
  // Ряды строки рекомендации (registerRec) — это dу, а #dsel хранит dн: переводим dу → dн.
  recKey(du){ for(const k in MAT_STEEL.gas.du) if(MAT_STEEL.gas.du[k]===du) return +k; return NaN; },
  // …и обратно: значение #dsel → значение того же ряда (для проверки «совпал ли выбранный диаметр»).
  rowValue(d){ const u=MAT_STEEL.gas.du[d]; return u===undefined?NaN:u; },
  // Строка «Диаметр условного прохода dу= … трубы лёгкие/обыкновенные/усиленные» (Label13 + строки
  // 0x4418a0/c0/ec). dу — Таблица 1 кн. Шевелевых 1984; «обыкновенная» стенка задана орд-таблицей ord
  // (по книжному dв: у 21,3/26,8 из четырёх — 2,8), иначе «обыкновенная» — вторая в списке.
  duLine(st,d){ const w=MAT_STEEL.gas.s[d]||[]; if(!w.length) return '';
   const ord=MAT_STEEL.gas.ord[d]!==undefined?MAT_STEEL.gas.ord[d]:w[1];
   const typ=st.S===ord?'обыкновенные':(st.S===Math.max(...w)?'усиленные':'легкие');
   return `Диаметр условного прохода dу=${MAT_STEEL.gas.du[d]}\nтрубы ${typ}`; },
  // Порог блока местных сопротивлений: при dу ≥ 80 (dн ≥ 88,5 по ГОСТ 3262-75) программа убирает
  // строки «учесть потери…», «Режим» и k (живое наблюдение 10.10.2026; на малых диаметрах доступно).
  mestLimit(st,d){ const u=MAT_STEEL.gas.du[d]; return u!==undefined && u>=80; },
  // «другой» здесь открывает ТОЛЬКО ручной dp — выбор dн из списка остаётся доступным (frmtablII1).
  // ν/ρ по температуре из поля «t = … °C» (ГВС стали). ν — точная таблица EXE FUN_0047de20
  // (реверс 10.10.2026): 40…95 °C с шагом 5, две одинаковые цепочки; ρ — книжные пресеты
  // 10³·{0,99;0,98;0,98;0,97;0,97}. Раньше эта таблица стояла константой T_NU_RHO в ui.js.
  nuTable:T_NU_RHO_STEEL, rhoTable:RHO_STEEL,
  gated:false,
  // Рекомендация по ряду dу: берётся ПЕРВЫЙ, у которого v(его dв) ≤ VREC (порог из программы).
  // Ряд — дословно из BSTR (0x44fd4..0x4502c). При расходе, не влезающем ни в один ряд, программа
  // печатает «более 500мм» — текст приходит как готовый шаблон overflow.
  rec:{mode:'vel', rows:[100,150,200,250,300,350,400,500], clamp:false,
   overflow:q=>`Большая скорость! При расходе ${fmt2(q*1000)} л/сек = ${fmt2(q*3600)} м куб/ч рекомендуется использовать трубу с диаметром более 500мм`},
};
registerMaterial(MAT_STEEL);

