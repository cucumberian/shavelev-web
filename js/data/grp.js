/* js/data/grp.js — стеклопластиковые трубы (СП 40-104-2001).
   Данные — реверс shev.exe (BSTR-списки комбо + пулы f64); комментарии указывают
   VA-адреса находки. */
"use strict";

 // frmtablII? (СП 40-104-2001): список комбо — AddItem-последовательность загрузки страницы
  // FUN_005093e0 и её дубль FUN_0050b8c0: 50,60,80,90,110,150,175,200,215,265,300,315,400 (13 значений,
  // индексы 0..12). Строки 175/215/265 лежат в пуле прямо перед якорем sp40_104_2001.doc (0x447630),
  // сама страница идёт сразу за ж/б — атрибуция однозначна. Скрин оригинала 07.10.2026: в комбо есть
  // d=60 (прежний домысел 100…1200 значения 60 не содержал). dв = d (dp предзаполнен тем же 60).
  const MAT_GRP = {id:'grp',      name:'Стеклопластиковые СП 40-104-2001',                   doc:'sp40_104',
   d:[50,60,80,90,110,150,175,200,215,265,300,315,400], dvSame:true,
   // Карта видимости блоков страницы: режима/теплоносителя/k/«новые-неновые» в окне нет (H = i·L)
   ui:{sys:false, wear:false, cu:false}}

/* page — поведение страницы (рефакторинг 13.10.2026): чистые функции, без DOM.
   У стеклопластика dв = dу — в комбо только готовые диаметры (живой скрин 07.10.2026: d=60 → dp=60).
   d — #dsel хранит d (он же dв). */
MAT_GRP.page={
  // discovery — что о странице сообщает shev-list-materials: ряд диаметров (для серии,
  // выставленной в st), закон dв словами и, где есть, серии/классы труб. Знание здесь, а не в
  // ветвлении инструмента: прежняя цепь в webmcp.js однажды выдала metal-pex текст подписи стекла.
  discovery(st){ return {
    diameters:(this.rows(st)||[]).map(r=>r[0]),
    note:'dв=d (СП40-104-2001: 50…400 мм, 13 значений списка программы); «другой» — ручной dp'
  }; },
  labels:{d:'Внутренний диаметр, мм:', dv:'Расчётный внутренний диаметр dp, мм:'},
  rows(){ return MAT_GRP.d.map(d=>[d,'dв='+d+' мм']); },
  // У стеклопластика dв = dу — в комбо только готовые диаметры (живой скрин 07.10.2026: d=60 → dp=60).
  dvOf(st,d){ return +d; },
  gated:true,
};
registerMaterial(MAT_GRP);

/* экспорт для node-тестов */
if (typeof module!=='undefined' && module.exports){
  module.exports={MAT:MAT_GRP};
}
