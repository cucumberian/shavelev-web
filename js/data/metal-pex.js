/* js/data/metal-pex.js — металлополимерные трубы (PEX-AL-PEX).
   Ряд dн — объединение двух комбо программы (16,20,26,32,40,50 + 50…90).
   dв подставляет программа: dв = dн − 2S, S берётся из кода: 16→2, 20→2, 26→3, 32→3, 40→3,5, 50→4;
   для второй серии цепочки S нет, поэтому dв = dн (уточняется живым скрином).
   Живые точки 08.10.2026: dн=16 → dв=12 (v=8,842; i=8,122; H=812,218) и dн=40 → dв=33 (v=3,508; i=0,48).
   Формула — та же, что у PEX (Кэ=1·10⁻⁶, √λ = 0,5[b/2+1,312(2−b)]/(lgRe−1)); ν/ρ по t — как у PEX.
   Подробности реверса — в корневом ../AGENTS.md и materials/pex_re/metal_pex.md. */
"use strict";

const MAT_METAL_PEX = {
 id:'metal-pex',
 name:'Металлополимерные трубы (PEX-AL-PEX)',
 docs:['sp41_102_98','sp40_102_2000'],   // две синие ссылки, как в окне оригинала
 d:[16,20,26,32,40,50],
 dvMap:{16:12,20:16,26:20,32:26,40:33,50:42},
 dvSame:false,


 /* ν(t) на этой странице — ДВЕ разные цепочки по системе (живые точки 14.10.2026,
    materials/metal_pex_live_check.md):
      ГВС (hot):   50→0,66  60→0,55  70→0,47  80→0,41  90→0,36   (i=0,619 при t50; i=1,653 при t60;
                    i=0,178 при t70; i=0,054 при t90)
      отопление:   50→0,55  60→0,47  70→0,41  80→0,36  90→0,32   (R=7979,747 при t50; R=1500,397 при t80;
                    R=1025,342 при t90)
    Обе — из цепочки шести значений 0,66…0,32 (@0x527da9 и дубль @0x5281b7): ветка ГВС берёт её с
    первого элемента, ветка отопления — со второго. Прежняя одна таблица {0,55…0,32} была верна
    только для отопления. */
 tHot:[{t:50,rho:990,nu:0.66e-6},{t:60,rho:980,nu:0.55e-6},{t:70,rho:980,nu:0.47e-6},
       {t:80,rho:970,nu:0.41e-6},{t:90,rho:970,nu:0.36e-6}],
 tHeat:[{t:50,rho:990,nu:0.55e-6},{t:60,rho:980,nu:0.47e-6},{t:70,rho:980,nu:0.41e-6},
        {t:80,rho:970,nu:0.36e-6},{t:90,rho:970,nu:0.32e-6}],

  // Карта видимости блоков страницы: стального блока и «новые/неновые» нет;
  // свои рамки «Выбор системы» (3 Option)/«Температура»/«Теплоноситель»/ξ — как у PEX
  ui:{sys:false, wear:false, cu:true}
}

/* page — поведение страницы (рефакторинг 13.10.2026): чистые функции, без DOM.
   dв подставляет программа по таблице dvMap (живые точки 08.10.2026: dн=16 → 12, v=8,842; i=8,122;
   H=812,218; dн=40 → 33, v=3,508; i=0,48; H=47,976). d — #dsel хранит НАРУЖНЫЙ dн. */
MAT_METAL_PEX.page={
  // discovery — что о странице сообщает shev-list-materials: ряд диаметров (для серии,
  // выставленной в st), закон dв словами и, где есть, серии/классы труб. Знание здесь, а не в
  // ветвлении инструмента: прежняя цепь в webmcp.js однажды выдала metal-pex текст подписи стекла.
  discovery(st){ return {
    diameters:(this.rows(st)||[]).map(r=>r[0]),
    note:'diameter_mm=dн (ряд живого окна 10.10.2026: 16, 20, 26, 32, 40, 50 мм); dв подставляет программа: 16→12, 20→16, 26→20, 32→26, 40→33, 50→42; «другой dв» — ручной dp; местные сопротивления — ξ (xi_total в shev-losses)'
  }; },
  // Карта систем Frame2 «Выбор системы» — у всех трёх СП-страниц своя: у меди это Option1–4
  // (шаблон 0x6fb58), у PEX и ПЭ-АЛ-ПЭ — Option1–3 (слоты 0x388/0x38c/0x384).
  // Ключи: cap — подпись кнопки, lim — предел скорости, note — текст предупреждения,
  // cold / t / heat — активность блоков и требуется ли температура (см. spSysSync).
   sys:{cold:{cap:'холодного водоснабжения',lim:4,cold:true,
        note:'Для систем холодного водоснабжения рекомендуется скорость до 4 м/сек'},
       hot:{cap:'горячего водоснабжения',lim:3,t:true,
        note:'Для систем ГВС рекомендуется скорость до 3 м/сек'},
       heat:{cap:'отопления',lim:2,heat:true,
        note:'Для систем отопления рекомендуется скорость до 2 м/сек'}},  // У ПЭ-АЛ-ПЭ свой ряд (16,20,26,32,40,50) и своя карта dв — строки сортамента с [S,ΔS,Δd] нет.
  seriesRow(){ return null; },
  // ── СП-семейство (общий контракт страниц меди / PEX / PEX-AL-PEX) ───────────────────────────
  kind:'sp',
  blocks:['cuSysField','cuTField','cuHeatField','xiField'],   // свои блоки вместо стальных
  // Формула страницы. Здесь одна λ на ВСЕ три системы (СП 41-109-2005 п.3.5, вариант СП 40-102-2000),
  // а не три ветки как у меди. i = λV²/(2·9,81·d) — Variant 9,81 @0x528e10 в EXE; здесь 2G = 19,6133 (решение 13.10.2026). R = λV²/(2d)·10³ Па/м.
  // Галка «считать по формуле (4) СП» выбирает вариант СП с множителем lg(3,7d/Кэ) внутри скобки —
  // внутри программы его нет (см. комментарий у pexLambda в formulas.js).
  // law: вариант программы (код FUN_00526810) или формула (4) СП — галка «считать по (4) СП».
  loss(S,nu,v,d,rho,sp){ const lam=sp?pexLambdaSP(nu,v,d):pexLambda(nu,v,d);
    return {law:sp?'pexSP':'pex', i:lam*v*v/(2*G*d), R:lam*v*v/(2*d)*CU.K1000}; },
  // ν и ρ для теплоносителя «вода» по температуре из Frame4: строки табл. 2 СП 41-109-2005 для
  // t = 5…20 °C в EXE нет, поэтому при t<50 возвращаем null — умолчания берут UI и движок.
  // У ПЭ 100 этой таблицы нет вовсе (там нет блока «Температура»).
  // S — запись из page.sys (у отопления флаг heat:true), не строка: см. spFluid в calc.js
  fluid(S,t){ const list=S&&S.heat?MAT_METAL_PEX.tHeat:MAT_METAL_PEX.tHot;
    const row=(t==null)?null:list.filter(r=>r.t<=t).pop();
    if(!row) return null;
    return {nu:row.nu, rho:row.rho}; },
  // Подписи вывода — строки шаблона формы frmtablII10, они отличаются от меди: в строке i нет
  // «(1000i = …)», для холодного и горячего водоснабжения потери давления печатаются ЦЕЛЫМИ
  // паскалями, для отопления — тремя знаками и другой формулировкой, а строки про падение давления
  // в системе отопления нет вовсе (поля drop у страницы нет).
  out:{iWith1000:false,
   rHeat :R   =>`R = ${fmt3(R)} Па/м`,
   dP    :P   =>`потери давления = ${fmt(P,0)} Па`,
   dPHeat:P   =>`Потери давления на участке ${fmt3(P)} Па`},
  // Список ξ (те же 12 позиций, что у меди — Variant-константы calc 0x526810 @0x529fcc…0x52a160)
  xi:[['отвод 90°',0.5],['тройник на проход',0.5],['тройник на ответвление',1.5],
     ['тройник на слияние',1.5],['тройник на разделение потока',3],['крестовина на проход',2],
     ['крестовина на ответвление',3],['отступ',0.5],['скоба',1],['внезапное расширение',0.5],
     ['внезапное сужение',1],['соединение с обжимной гайкой',1.5]],
  blocks:['pexSpRow'],              // галка «считать по формуле (4) СП» доступна и здесь
  labels:{d:'Наружный диаметр dн, мм:', dv:'Внутренний диаметр dв, мм:'},
  rows(){ return MAT_METAL_PEX.d.map(d=>[d,'dн='+d+' мм']); },
  gated:true,                        // Check13 «другой dв» в окне есть — dv_mm принимается
  // dв подставляет программа по таблице dvMap (живые точки 08.10.2026: dн=16 → 12, v=8,842; i=8,122;
  // H=812,218; dн=40 → 33, v=3,508; i=0,48; H=47,976).
  dvOf(st,d){ const x=MAT_METAL_PEX.dvMap[+d]; return x===undefined?NaN:x; },
};
