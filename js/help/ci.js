/* Состояние расчёта чугунной страницы: те же контролы и тот же движок, что в ui.js. */
function ciHelpState(){
 const m=currentMat(); if(!m||m.id!=='ci') return null;
 const qRaw=numStrict($('q').value), L=numStrict($('len').value), dv=curDv();
 if(isNaN(qRaw)||isNaN(dv)||dv<=0||isNaN(L)) return null;
 const wear=(rad('wear')||{}).value||'old';
 const r=shevCalc({mat:'ci',wear:wear,dv_mm:dv,q:qRaw,qunit:$('qunit').value,L:L,
   k:0,mest:false,nu:numStrict($('nu').value),rho:numStrict($('rho').value),mode:$('mode').value});
 if(!r.ok) return null;
 const cls=curCls(), du=+$('dsel').value;
 const t=(m.cls&&m.cls[cls]&&m.cls[cls][du])||[du,0];   // страховка; недостижима: 16 строк есть у всех трёх классов, включая dу=1000
 const dv0=t[0]-2*t[1], d=dv/1000;
 return {wear:wear,r:r,qRaw:qRaw,qm3:qToM3s(qRaw,$('qunit').value),dv:dv,du:du,cls:cls,dn:t[0],S:t[1],dv0:dv0,
   L:L,d:d,manual:$('danother').checked,lam:r.A*G2/Math.pow(d,r.e-1)};
}

