function ciHelpStep(kind){
 const st=ciHelpState(); if(!st) return '';
 const r=st.r, f=fmt, v=r.v, i=r.i, d=st.d, L=st.L;
 const N=(sub,res)=>({sub:sub,res:res}); // строку собирает js/help.js (общий пайплайн)
 const iRes=f(i*1000,3)+' мм/м (i = '+f(i,6)+' м/м)';
 switch(kind){
  case 'q': {
   const sub=($('qunit').value==='mh')? ('\\frac{'+f(st.qRaw,3)+'}{3600}') : ('\\frac{'+f(st.qRaw,3)+'}{1000}');
   return N(sub, f(st.qm3,6)+' м³/с');
  }
  case 'dp': {
   if(st.manual) return N(f(st.dv,2), f(st.dv,2)+' мм <span class="fParam">ручной ввод (флажок «другой»)</span>');
   const minus=(st.wear==='old');   // «неновые»: −1 мм при любом диаметре (живые точки 13.10.2026)
   const sub=minus
     ? ('d_p=d_{\\text{н}}-2S-1='+f(st.dn,1)+'-2\\cdot '+f(st.S,2)+'-1')
     : ('d_p=d_{\\text{в}}=d_{\\text{н}}-2S='+f(st.dn,1)+'-2\\cdot '+f(st.S,2));
   return N(sub, f(st.dv,2)+' мм <span class="fParam">класс '+st.cls+', d_{\\text{н}} = '+f(st.dn,1)+' мм, S = '+f(st.S,2)+' мм, d_{\\text{в}} = '+f(st.dv0,2)+' мм</span>');
  }
  case 'v': return N('\\frac{'+f(st.qm3,6)+'\\cdot 4}{\\pi\\cdot '+f(d,5)+'^2}', f(v,3)+' м/с');
  case 'lam_new': return N('\\frac{0,0144}{'+f(d,5)+'^{0,284}}\\cdot\\left(1+\\frac{2,36}{'+f(v,3)+'}\\right)^{0,284}', 'λ = '+f(st.lam,8));
  case 'i_new': return N('\\frac{'+f(st.lam,8)+'\\cdot '+f(v,3)+'^2}{2\\cdot 9,80665\\cdot '+f(d,5)+'}', iRes);
  case 'i_hi': return N('\\frac{0,021}{19,6133}\\cdot\\frac{'+f(v,3)+'^2}{'+f(d,5)+'^{1,3}}', iRes);
  case 'i_lo': return N('0,000912\\cdot\\left(1+\\frac{0,867}{'+f(v,3)+'}\\right)^{0,3}\\cdot\\frac{'+f(v,3)+'^2}{'+f(d,5)+'^{1,3}}', iRes);
  case 'R': return N('1000\\cdot 9,80665\\cdot '+f(i,6), f(r.R,1)+' Па/м');
  case 'H': return N(f(L,0)+'\\cdot '+f(i,6), f(r.H,3)+' м');
  case 'P': return N(f(r.R,1)+'\\cdot '+f(L,0), f(r.P,0)+' Па');
 }
 return '';
}

