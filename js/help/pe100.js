/* js/help/pe100.js — справка страницы pe100 (полиэтиленовые трубы ПЭ 100, ГОСТ Р 70628.2-2023):
   раздел «Расчёты» — формулы в порядке вычисления, подстановка текущих данных и результат.
   Контракт — js/help.js (registerHelp/renderCalcHelp), рендер формул — js/tex.js.
   Числа берутся из того же движка, что и расчёт страницы (js/calc.js + js/formulas.js), из тех же
   полей, поэтому подстановка совпадает с выводом.

   ВАЖНО о происхождении данных. Это страница КЛОНА: в оригинальной программе её нет (там страница
   пластмассовых труб сделана по ГОСТ 18599-2001). Сортамент — табл. 1 и 2 ГОСТ Р 70628.2-2023
   (ИСО 4427-2:2019, MOD), офлайн-копия — docs/gost-r-70628-2023/. Гидравлики новый стандарт не
   содержит вовсе, поэтому i считается той же формулой (8) книги Шевелевых 1984, что и на странице
   ГОСТ 18599-2001: труба та же, полиэтилен тот же. */
"use strict";

/* Состояние расчёта страницы ПЭ 100: читаем ровно те же контролы, что ui.js, и считаем тем же
   движком (shevCalc), поэтому все подставляемые числа равны выводу страницы. */
function pe100HelpState(){
 const m=currentMat(); if(!m||m.id!=='pe100') return null;
 const qRaw=numStrict($('q').value), L=numStrict($('len').value), dv=curDv();
 if(isNaN(qRaw)||isNaN(dv)||dv<=0||isNaN(L)) return null;
 const sdr=pe100Series(), dn=parseFloat($('dsel').value);
 const ser=m.pe100[sdr]||null, cell=ser?ser.dn[dn]:null;
 const r=shevCalc({mat:'pe100',wear:'old',dv_mm:dv,q:qRaw,qunit:$('qunit').value,L:L,
   k:0,mest:false,nu:numStrict($('nu').value),rho:numStrict($('rho').value),mode:$('mode').value,
   selD:dn, dpOf:d=>{const c=ser&&ser.dn[d];return !c?NaN:d-2*c[0];}});
 if(!r.ok) return null;
 return {r:r,qRaw:qRaw,qm3:qToM3s(qRaw,$('qunit').value),dv:dv,L:L,d:dv/1000,dn:dn,
   e:cell?cell[0]:undefined,emax:cell?cell[1]:undefined,sdr:sdr,pn:ser?ser.pn:null,
   s:ser?ser.s:null,manual:$('danother').checked};
}

