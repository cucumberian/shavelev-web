"use strict";

/* Состояние расчёта стеклопластиковой страницы: те же контролы и тот же движок, что в ui.js. */
function grpHelpState(){
 const m=currentMat(); if(!m||m.id!=='grp') return null;
 const qRaw=numStrict($('q').value), L=numStrict($('len').value), dv=curDv();
 if(isNaN(qRaw)||isNaN(dv)||dv<=0||isNaN(L)) return null;
 const r=shevCalc({mat:'grp',wear:'old',dv_mm:dv,q:qRaw,qunit:$('qunit').value,L:L,
   k:0,mest:false,nu:numStrict($('nu').value),rho:numStrict($('rho').value),mode:$('mode').value,
   selD:parseFloat($('dsel').value), dpOf:d=>d});
 if(!r.ok) return null;
 return {r:r,qRaw:qRaw,qm3:qToM3s(qRaw,$('qunit').value),dv:dv,L:L,d:dv/1000,
   dsel:parseFloat($('dsel').value),manual:$('danother').checked,lam:r.A*G2};
}

