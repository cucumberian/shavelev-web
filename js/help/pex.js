/* Подстановка текущих данных: «= <формула с числами> = <результат с единицами>». */
function pexHelpStep(kind){
 const st=pexHelpState(); if(!st) return '';
 const r=st.r, f=fmt, v=st.v, d=st.d, L=st.L;
 const N=(sub,res)=>({sub:sub,res:res}); // строку собирает js/help.js (общий пайплайн)
 switch(kind){
  case 'q': {
   const sub=($('qunit').value==='mh')? ('\\frac{'+f(st.qRaw,3)+'}{3600}') : ('\\frac{'+f(st.qRaw,3)+'}{1000}');
   return N(sub, f(st.qm3,6)+' м³/с');
  }
  case 'dp': {
   if(st.manual) return N(f(st.dv,2), f(st.dv,2)+' мм <span class="fParam">ручной ввод (флажок «другой dв»)</span>');
   const rw=st.row; if(!rw) return '';
   return N('0,5\\left(2\\cdot '+f(st.dn,2)+'+'+f(rw[2],2)+'-4\\cdot '+f(rw[0],2)+'-2\\cdot '+f(rw[1],2)+'\\right)',
     f(st.dv,2)+' мм <span class="fParam">серия «'+st.serCap+'»: S = '+f(rw[0],2)+', ΔS = '+f(rw[1],2)+', Δd = '+f(rw[2],2)+' мм (табл. 1 СП 41-109-2005)</span>');
  }
  case 'v': return N('\\frac{'+f(st.qm3,6)+'\\cdot 4}{\\pi\\cdot '+f(d,5)+'^{2}}', f(v,3)+' м/с');
  case 're': return N('\\frac{'+f(d,5)+'\\cdot '+f(v,3)+'}{'+f(st.nu*1e6,2)+'\\cdot 10^{-6}}', f(st.re,0));
  case 'rek': return N('\\frac{500\\cdot '+f(d,5)+'}{1,0\\cdot 10^{-6}}', f(st.rek,0)+' <span class="fParam">К_{\\text{э}} = 1,0·10⁻⁶ м</span>');
  case 'b': return N('1+\\frac{\\lg '+f(st.re,0)+'}{\\lg '+f(st.rek,0)+'}', f(st.b,4)+(st.capB?' <span class="fParam">b &gt; 2 — принято b = 2</span>':''));
  case 'lamSp': return N('0,5\\left(\\frac{'+f(st.b,4)+'}{2}+\\frac{1,312(2-'+f(st.b,4)+')\\cdot '+f(st.l37,4)+'}{\\lg '+f(st.re,0)+'-1}\\right)\\Big/'+f(st.l37,4),
     '√λ = '+f(Math.sqrt(st.lamSP),6)+' (λ = '+f(st.lamSP,6)+')');
  case 'lamProg': return N('0,5\\left(\\frac{'+f(st.b,4)+'}{2}+1,312(2-'+f(st.b,4)+')\\right)\\Big/\\left(\\lg '+f(st.re,0)+'-1\\right)',
     '√λ = '+f(Math.sqrt(st.lamPr),6)+' (λ = '+f(st.lamPr,6)+')');
  case 'i': return N('\\frac{'+f(st.sp?st.lamSP:st.lamPr,6)+'\\cdot '+f(v,3)+'^{2}}{2\\cdot 9,80665\\cdot '+f(d,5)+'}', f(r.i,3)+' м/м');
  case 'R': return N('\\frac{'+f(st.sp?st.lamSP:st.lamPr,6)+'\\cdot '+f(v,3)+'^{2}}{2\\cdot '+f(d,5)+'}\\cdot 10^{3}', fmt3(r.R)+' Па/м');
  case 'Z': return N(f(r.xi,2)+'\\cdot\\frac{'+f(v,3)+'^{2}}{2}\\cdot '+f(st.rho,0), fmt3(r.Z)+' Па <span class="fParam">Σξ = '+f(r.xi,2)+'</span>');
  case 'H': return N(f(L,0)+'\\cdot '+f(r.i,6)+'+\\frac{'+f(v,3)+'^{2}\\cdot '+f(r.xi,2)+'}{2\\cdot 9,80665}', fmt3(r.H)+' м <span class="fParam">Σξ = '+f(r.xi,2)+'</span>');
  case 'P': return N(fmt3(r.R)+'\\cdot '+f(L,0)+'+'+fmt3(r.Z), (st.sys==='heat'?fmt3(r.P):fmt(r.P,0))+' Па');
 }
 return '';
}

