function asbesHelpStep(kind){
 const st=asbesHelpState(); if(!st) return '';
 const r=st.r, f=fmt, v=r.v, i=r.i, d=st.d, L=st.L;
 const N=(sub,res)=>({sub:sub,res:res}); // строку собирает js/help.js (общий пайплайн)
 const iRes=f(i*1000,3)+' мм/м (i = '+f(i,6)+' м/м)';
 switch(kind){
  case 'q': {
   const sub=($('qunit').value==='mh')? ('\\frac{'+f(st.qRaw,3)+'}{3600}') : ('\\frac{'+f(st.qRaw,3)+'}{1000}');
   return N(sub, f(st.qm3,6)+' м³/с');
  }
  case 'dp': return st.manual
   ? N(f(st.dv,2), f(st.dv,2)+' мм <span class="fParam">ручной ввод (флажок «другой»)</span>')
   : N(f(st.dv,2), f(st.dv,2)+' мм <span class="fParam">ГОСТ 539-80: '+st.vt+', тип '+st.tip+', dу '+st.du+' мм</span>');
  case 'v': return N('\\frac{'+f(st.qm3,6)+'\\cdot 4}{\\pi\\cdot '+f(d,5)+'^2}', f(v,3)+' м/с');
  case 'i': return N('0,000561\\cdot\\frac{'+f(v,3)+'^2}{'+f(d,5)+'^{1,190}}\\cdot\\left(1+\\frac{3,51}{'+f(v,3)+'}\\right)^{0,190}', iRes);
  case 'R': return N('1000\\cdot 9,80665\\cdot '+f(i,6), f(r.R,1)+' Па/м');
  case 'H': return N(f(L,0)+'\\cdot '+f(i,6), f(r.H,3)+' м');
  case 'P': return N(f(r.R,1)+'\\cdot '+f(L,0), f(r.P,0)+' Па');
 }
 return '';
}

