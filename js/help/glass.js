/* js/help/glass.js — справка страницы glass (стеклянные трубы, ГОСТ 8894-86):
   раздел «Расчёты» — формулы в порядке вычисления, подстановка текущих данных и результат.
   Контракт — js/help.js (registerHelp/renderCalcHelp), рендер формул — js/tex.js (LaTeX: KaTeX,
   иначе встроенный мини-рендер). Числа берутся из того же движка, что и расчёт страницы
   (js/calc.js + js/formulas.js), из тех же полей, поэтому подстановка совпадает с выводом.
   Источники: кн. Шевелевых Ф.А. и др., «Таблицы для гидравлического расчета водопроводных труб»,
   1984 — формула (9) для стеклянных труб и общая формула (1); ГОСТ 8894-86 (наружные dн 45…221,
   внутренние dв — таблица программы); восстановленные формулы js/formulas.js
   (A = 0,000745·v^(−0,226), e = 1,226); комментарии js/data/glass.js; тексты справки EXE (frmhelp8). */
"use strict";

/* Состояние расчёта стеклянной страницы: те же контролы и тот же движок, что в ui.js. */
function glassHelpState(){
 const m=currentMat(); if(!m||m.id!=='glass') return null;
 const qRaw=numStrict($('q').value), L=numStrict($('len').value), dv=curDv();
 if(isNaN(qRaw)||isNaN(dv)||dv<=0||isNaN(L)) return null;
 const r=shevCalc({mat:'glass',wear:'old',dv_mm:dv,q:qRaw,qunit:$('qunit').value,L:L,
   k:0,mest:false,nu:numStrict($('nu').value),rho:numStrict($('rho').value),mode:$('mode').value,
   selD:parseFloat($('dsel').value), dpOf:d=>m.dvMap[d]===undefined?NaN:m.dvMap[d]});
 if(!r.ok) return null;
 return {r:r,qRaw:qRaw,qm3:qToM3s(qRaw,$('qunit').value),dv:dv,L:L,d:dv/1000,
   dn:parseFloat($('dsel').value),manual:$('danother').checked};
}

