/* Состояние расчёта страницы пластика: читаем ровно те же контролы, что ui.js, и считаем тем же
   движком (shevCalc), поэтому все подставляемые числа равны выводу страницы. */
function plasticHelpState(){
 const m=currentMat(); if(!m||m.id!=='plastic') return null;
 const qRaw=numStrict($('q').value), L=numStrict($('len').value), dv=curDv();
 if(isNaN(qRaw)||isNaN(dv)||dv<=0||isNaN(L)) return null;
 const pe=curPe(), sdr=curSdr(), dn=parseFloat($('dsel').value);
 const col=(m.pe[pe]&&m.pe[pe][sdr])?m.pe[pe][sdr]:null;
 const r=shevCalc({mat:'plastic',wear:'old',dv_mm:dv,q:qRaw,qunit:$('qunit').value,L:L,
   k:0,mest:false,nu:numStrict($('nu').value),rho:numStrict($('rho').value),mode:$('mode').value,
   selD:dn, dpOf:d=>{const sd=m.pe[pe]&&m.pe[pe][sdr];return (!sd||sd[d]===undefined)?NaN:d-2*sd[d];}});
 if(!r.ok) return null;
 return {r:r,qRaw:qRaw,qm3:qToM3s(qRaw,$('qunit').value),dv:dv,L:L,d:dv/1000,dn:dn,
   e:col?col[dn]:undefined,pe:pe,sdr:sdr,manual:$('danother').checked};
}

