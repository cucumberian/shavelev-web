  S.i=line('\\frac{'+f(lam,6)+'\\cdot '+f(v,3)+'^2}{2\\cdot 9,81\\cdot '+f(d,5)+'}',f(i,3)+' м/м');
  S.R=line('\\frac{'+f(lam,6)+'\\cdot '+f(v,3)+'^2}{2\\cdot '+f(d,5)+'}\\cdot 10^3',f(R,3)+' Па/м');
