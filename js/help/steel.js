/* Подстановка текущих данных: «= <формула с числами> = <результат с единицами>». */
function steelHelpStep(kind,id){
 const st=steelHelpState(); if(!st) return '';
 const r=st.r, f=fmt, v=r.v, i=r.i, d=st.d, L=st.L, rho=r.rho, k=(isNaN(r.k)?0:r.k); // пустой k = 0 (как считает движок)
 const N=(sub,res)=>({sub:sub,res:res}); // строку собирает js/help.js (общий пайплайн)
 const iRes=f(i*1000,3)+' мм/м (i = '+f(i,6)+' м/м)';
 const gas=id==='steel';
 switch(kind){
  case 'q': {
   const sub=($('qunit').value==='mh')? ('\\frac{'+f(st.qRaw,3)+'}{3600}') : ('\\frac{'+f(st.qRaw,3)+'}{1000}');
   return N(sub, f(st.qm3,6)+' м³/с');
  }
  case 'v': return N('\\frac{'+f(st.qm3,6)+'\\cdot 4}{\\pi\\cdot '+f(d,5)+'^2}', f(v,3)+' м/с');
  case 'dp': {
   if(st.manual) return N(f(st.dv,2), f(st.dv,2)+' мм <span class="fParam">ручной ввод (флажок «другой»)</span>');
   const sub='d_p='+f(st.dn,2)+'-2\\cdot '+f(st.S,2)+'-1';
   return N(sub, f(st.dv,2)+' мм');
  }
  case 'i_new': return N('\\frac{'+f(st.lam,8)+'\\cdot '+f(v,3)+'^2}{2\\cdot 9,81\\cdot '+f(d,5)+'}', iRes);
  case 'i_hi': return N('\\frac{0,021}{19,62}\\cdot\\frac{'+f(v,3)+'^2}{'+f(d,5)+'^{1,3}}', iRes);
  case 'lam_new': return N('\\frac{0,312}{'+f(d,5)+'^{0,226}}\\cdot\\left(1,9\\cdot10^{-6}+\\frac{'+f(st.nu*1e6,3)+'\\cdot10^{-6}}{'+f(v,3)+'}\\right)^{0,226}', 'λ = '+f(st.lam,8)+' (ν = '+f(st.nu*1e6,3)+'·10⁻⁶ м²/с)');
  case 'i_lo': return N('\\frac{\\left(1,5\\cdot10^{-6}+\\frac{'+f(st.nu*1e6,3)+'\\cdot10^{-6}}{'+f(v,3)+'}\\right)^{0,3}}{'+f(d,5)+'^{0,3}}\\cdot\\frac{'+f(v,3)+'^2}{2\\cdot 9,81\\cdot '+f(d,5)+'}', iRes);
  case 'R': return N(f(rho,0)+'\\cdot 9,80665\\cdot '+f(i,6), f(r.R,1)+' Па/м');
  case 'H': return N(f(L,0)+'\\cdot '+f(i,6)+'\\cdot(1+'+f(k,2)+')', f(r.H,3)+' м');
  case 'P': return N(f(r.R,1)+'\\cdot '+f(L,0)+'\\cdot(1+'+f(k,2)+')', f(r.P,0)+' Па');
 }
 return '';
}

