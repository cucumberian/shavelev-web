/* js/help/steel.js — справка страницы steel (стальные водогазопроводные, ГОСТ 3262-75):
   раздел «Расчёты» — формулы в порядке вычисления, подстановка текущих данных и результат.
   Контракт — js/help.js (registerHelp/renderCalcHelp), рендер формул — js/tex.js (LaTeX: KaTeX,
   иначе встроенный мини-рендер). Числа берутся из того же движка, что и расчёт страницы
   (js/calc.js + js/formulas.js), из тех же полей, поэтому подстановка совпадает с выводом.
   Источники: кн. Шевелевых Ф.А. и др., «Таблицы для гидравлического расчета водопроводных труб»,
   1984 — формулы (1), (2), (2а), (4), (5а), (6), (7), табл. 1 и стр. 6; восстановленные формулы
   js/formulas.js; комментарии js/data/steel.js; тексты справки EXE (frmtablII1).
   steelHelpPage(id) обслуживает обе стальные страницы (steel и steel-es) — вторая регистрируется
   в js/help/steel-es.js, который подключается сразу после этого файла. */
"use strict";

/* Состояние расчёта стальной страницы: читаем ровно те же контролы, что ui.js, и считаем тем же
   движком (shevCalc), поэтому все подставляемые числа равны выводу страницы. */
function steelHelpState(){
 const m=currentMat(); if(!m||(m.id!=='steel'&&m.id!=='steel-es')) return null;
 const qRaw=numStrict($('q').value), L=numStrict($('len').value), dv=curDv();
 if(isNaN(qRaw)||isNaN(dv)||dv<=0||isNaN(L)) return null;
 const wear=(document.querySelector('input[name=wear]:checked')||{}).value||'old';
 const r=shevCalc({mat:m.id,wear:wear,dv_mm:dv,q:qRaw,qunit:$('qunit').value,L:L,
    k:numStrict($('k').value),mest:$('chkMest').checked,nu:numStrict($('nu').value),
    rho:numStrict($('rho').value),mode:$('mode').value});
 if(!r.ok) return null;
 const dn=parseFloat($('dsel').value), S=parseFloat($('tsel').value), d=dv/1000;
 const nu0=(!isNaN(r.nu)&&r.nu>0)?r.nu:1.3e-6;             // ν входит в формулы стали (EXE)
 const vsel=r.v/nu0;                                      // селектор ветки: v/ν, порог 9,2·10⁵ 1/м (EXE)
 return {id:m.id,wear:wear,r:r,qRaw:qRaw,qm3:qToM3s(qRaw,$('qunit').value),dv:dv,dn:dn,S:S,
    L:L,d:d,manual:$('danother').checked,nu:nu0,sel:vsel,lam:r.A*G2/Math.pow(d,r.e-1)}; // ν и v/(d·ν) — селектор ветки (EXE)
}

